#!/usr/bin/env node
/**
 * Generates one Code Connect mapping per icon: src/components/icons/IconX.figma.ts
 *
 * Why generated: the 55 icons are trivial, identical mappings (`<IconX />`), so
 * hand-writing them invites drift. The Figma node of each icon is looked up by
 * name in the official file (FIGMA_FILE_KEY, "Nova｜Master"): Figma component
 * "Icon / Arrow Right" ↔ code `IconArrowRight` (src/components/icons/IconArrowRight.tsx).
 *
 * Only icons that exist in BOTH places get a mapping (never map a component
 * that does not exist in code). Icons present on only one side are reported.
 * Read-only against Figma (GET /v1/files/:key/components).
 *
 * Usage:
 *   node scripts/figma/generate-icon-code-connect.mjs          # write files
 *   node scripts/figma/generate-icon-code-connect.mjs --check  # exit 1 if any file is missing/stale
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

try {
  process.loadEnvFile('.env');
} catch {
  // fall back to the existing environment
}

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const ICON_DIR = resolve(ROOT, 'src/components/icons');
// The URL keeps the canonical file key; figma.config.json's
// documentUrlSubstitutions swaps it for FIGMA_FILE_KEY at publish time.
const CANONICAL_KEY = 'fSzxt8wKkXsn8fmxkPBUr2';
const CHECK = process.argv.includes('--check');
// Figma placeholders that are not icons; mapped by hand (see the file named here).
const PLACEHOLDERS = new Map([['IconEmpty', 'EmptyIcon.figma.ts (renders nothing)']]);

const token = process.env.FIGMA_ACCESS_TOKEN;
const fileKey = process.env.FIGMA_FILE_KEY;
if (!token || !fileKey) {
  console.error('[icons] FIGMA_ACCESS_TOKEN and FIGMA_FILE_KEY are required (.env)');
  process.exit(1);
}

/** "Icon / Arrow Right" → "IconArrowRight" */
export function codeName(figmaName) {
  return (
    'Icon' +
    figmaName
      .slice('Icon / '.length)
      .split(/[\s/-]+/)
      .filter(Boolean)
      .map((w) => w[0].toUpperCase() + w.slice(1))
      .join('')
  );
}

/** "IconArrowRight" → "icon-arrow-right" (Code Connect id, used by nested templates) */
const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

export function template(name, nodeId) {
  return `// url=https://www.figma.com/design/${CANONICAL_KEY}/SunDesignSystem?node-id=${nodeId.replace(':', '-')}
// source=src/components/icons/${name}.tsx
// component=${name}
//
// GENERATED by scripts/figma/generate-icon-code-connect.mjs — do not edit by hand.
// Lets nested icon instances (Button prefix/suffix, Icon Button, TextField
// adornments…) render as real code via executeTemplate().
import figma from 'figma';

export default {
  example: figma.code\`<${name} />\`,
  imports: ['import { ${name} } from "@sun-asterisk/nova/icons"'],
  id: '${kebab(name)}',
  metadata: { nestable: true },
};
`;
}

const res = await fetch(`https://api.figma.com/v1/files/${fileKey}/components`, {
  headers: { 'X-Figma-Token': token },
});
if (!res.ok) {
  console.error(`[icons] Figma API ${res.status}: ${await res.text()}`);
  process.exit(1);
}
const figmaIcons = new Map();
for (const c of (await res.json()).meta.components) {
  if (c.name.startsWith('Icon / ')) figmaIcons.set(codeName(c.name), c);
}

const codeIcons = readdirSync(ICON_DIR)
  .filter((f) => /^Icon[A-Z]\w*\.tsx$/.test(f))
  .map((f) => f.slice(0, -'.tsx'.length))
  .sort();

// Format exactly as `eslint --fix` (prettier) would, so --check stays stable.
const prettier = await import('prettier');
let stale = 0;
for (const name of codeIcons) {
  const fig = figmaIcons.get(name);
  if (!fig) continue;
  const path = resolve(ICON_DIR, `${name}.figma.ts`);
  const options = (await prettier.resolveConfig(path)) ?? {};
  const content = await prettier.format(template(name, fig.node_id), {
    ...options,
    filepath: path,
  });
  if (existsSync(path) && readFileSync(path, 'utf8') === content) continue;
  stale++;
  if (CHECK) console.error(`[icons] missing or stale: ${name}.figma.ts`);
  else writeFileSync(path, content);
}

const codeOnly = codeIcons.filter((n) => !figmaIcons.has(n));
const figmaOnly = [...figmaIcons.keys()]
  .filter((n) => !codeIcons.includes(n) && !PLACEHOLDERS.has(n))
  .sort();
const mapped = codeIcons.length - codeOnly.length;
console.log(`[icons] ${mapped} mapped, ${CHECK ? `${stale} stale` : `${stale} written`}`);
if (codeOnly.length)
  console.log(`[icons] in code, not in Figma (no mapping): ${codeOnly.join(', ')}`);
if (figmaOnly.length)
  console.log(`[icons] in Figma, not in code (no mapping): ${figmaOnly.join(', ')}`);
if (CHECK && stale) process.exit(1);
